//! The one place that knows the sandbox backend: turns a launch's merged `[sandbox]` table into a nono profile.
//!
//! The profile extends the table's base profile (`sandbox.base`, default `piton`, the profile piton used before
//! `[sandbox]` existed), adds its groups and grants, read access to every level of the configuration chain and the
//! files it reads, and write access to the source's workflow artifacts. The daemon writes it to its own state folder,
//! which no sandbox can reach, for each launch.
//!
//! Every path is literal in the profile: `~`, `$HOME`, and `$VAR` are expanded here from the daemon's own environment
//! (the login shell's, captured before any workspace's `mise env`), never left for nono to expand from pi's
//! environment, which a repository's `mise.toml` can set.

use std::path::{Path, PathBuf};

use serde_json::{Value, json};

use crate::config::{LOCAL_DIR, LaunchConfig, SandboxTable, expand_home};
use crate::launch::Env;

/// The base profile when the global tier names none.
pub const DEFAULT_BASE: &str = "piton";

#[derive(Debug, thiserror::Error)]
pub enum SandboxError {
    #[error("sandbox grant {grant:?}: ${var} isn't set in the daemon's environment")]
    UnsetVariable { grant: String, var: String },
    #[error("sandbox grant {grant:?}: expands to {expanded:?}, which isn't an absolute path")]
    NotAbsolute { grant: String, expanded: String },
}

/// The nono profile for one sandboxed launch. `env` is the daemon's base environment, for `$VAR` in grants;
/// `agent_socket` is the daemon's socket for sandboxed pis, which the profile lets them connect to (and nothing else of
/// the daemon's state folder).
pub fn profile(resolved: &LaunchConfig, home: &Path, env: &Env, agent_socket: &Path) -> Result<Value, SandboxError> {
    let table = &resolved.sandbox;
    let expand = |paths: &[String]| -> Result<Vec<String>, SandboxError> {
        paths.iter().map(|p| expand_grant(p, home, env)).collect()
    };

    let mut allow = expand(&table.allow)?;
    let artifacts = resolved.source.join(LOCAL_DIR);
    if artifacts.is_dir() {
        allow.push(artifacts.to_string_lossy().into_owned());
    }
    let mut read = expand(&table.read)?;
    for dir in chain_dirs(resolved) {
        let dir = dir.to_string_lossy().into_owned();
        if !read.contains(&dir) {
            read.push(dir);
        }
    }
    // Configuration entries can be links into a dotfiles repository; Seatbelt checks the target. A folder target
    // (a linked `rules/`) needs a recursive `read`; a file target a `read_file`.
    let mut read_file = expand(&table.read_file)?;
    for target in link_targets(resolved) {
        let is_dir = target.is_dir();
        let target = target.to_string_lossy().into_owned();
        if read.contains(&target) || read_file.contains(&target) {
            continue;
        }
        if is_dir {
            read.push(target);
        } else {
            read_file.push(target);
        }
    }

    let mut filesystem = serde_json::Map::new();
    let mut put = |key: &str, values: Vec<String>| {
        if !values.is_empty() {
            filesystem.insert(key.into(), json!(values));
        }
    };
    put("allow", allow);
    put("read", read);
    put("read_file", read_file);
    put("allow_file", expand(&table.allow_file)?);
    put("deny", expand(&table.deny)?);
    put("bypass_protection", expand(&table.bypass)?);
    let mut sockets = expand(&table.unix_socket)?;
    sockets.push(agent_socket.to_string_lossy().into_owned());
    put("unix_socket", sockets);

    let mut profile = json!({
        "meta": {"name": "piton-launch", "description": "Generated by the piton daemon for one launch"},
        "extends": table.base.clone().unwrap_or_else(|| DEFAULT_BASE.into()),
        "workdir": {"access": "readwrite"},
        "filesystem": filesystem,
        // Writes to protected files are denied to every process; the daemon writes them after the user approves.
        "unsafe_macos_seatbelt_rules": protected_roots(resolved).seatbelt_rules(),
    });
    if !table.groups.is_empty() {
        profile["groups"] = json!({"include": table.groups});
    }
    if let Some(network) = network(table) {
        profile["network"] = network;
    }
    Ok(profile)
}

/// The protected roots, canonical as Seatbelt compares them.
fn protected_roots(resolved: &LaunchConfig) -> crate::agent::ProtectedRoots {
    let canonical = |path: &Path| std::fs::canonicalize(path).unwrap_or_else(|_| path.to_path_buf());
    crate::agent::ProtectedRoots {
        source: canonical(&resolved.source),
        checkout: canonical(&resolved.checkout),
    }
}

/// A grant as a literal absolute path: `~` and `$HOME` from the user database, other `$VAR`s (a whole leading
/// segment, `$NAME` or `${NAME}`) from the daemon's base environment.
fn expand_grant(grant: &str, home: &Path, env: &Env) -> Result<String, SandboxError> {
    let path = expand_home(grant, home).to_string_lossy().into_owned();
    let expanded = match path.strip_prefix('$') {
        None => path,
        Some(rest) => {
            let (name, tail) = match rest.strip_prefix('{') {
                Some(braced) => braced.split_once('}').unwrap_or((braced, "")),
                None => rest.split_at(rest.find('/').unwrap_or(rest.len())),
            };
            let value = env
                .get(name)
                .filter(|v| !v.is_empty())
                .ok_or_else(|| SandboxError::UnsetVariable {
                    grant: grant.to_string(),
                    var: name.to_string(),
                })?;
            format!("{value}{tail}")
        }
    };
    if !expanded.starts_with('/') || expanded.contains('$') {
        return Err(SandboxError::NotAbsolute {
            grant: grant.to_string(),
            expanded,
        });
    }
    Ok(expanded)
}

/// The canonical targets of the configuration entries that are symlinks, so the sandbox can read through them (for
/// example the global tier's files, linked into a dotfiles repository): each entry of every level folder, and the
/// `rules` and `skills` folders under `.agents/` levels.
fn link_targets(resolved: &LaunchConfig) -> Vec<PathBuf> {
    let mut targets = Vec::new();
    let mut candidates = Vec::new();
    for level in &resolved.levels {
        if let Ok(entries) = std::fs::read_dir(level) {
            candidates.extend(entries.flatten().map(|entry| entry.path()));
        }
    }
    for path in candidates {
        let is_link = path.symlink_metadata().is_ok_and(|m| m.file_type().is_symlink());
        if is_link
            && let Ok(target) = std::fs::canonicalize(&path)
            && !targets.contains(&target)
        {
            targets.push(target);
        }
    }
    targets
}

fn network(table: &SandboxTable) -> Option<Value> {
    use crate::config::NetworkProfile;
    let mut network = serde_json::Map::new();
    if !table.network.open_port.is_empty() {
        network.insert("open_port".into(), json!(table.network.open_port));
    }
    match &table.network.profile {
        None => {}
        Some(NetworkProfile::Named(name)) => {
            network.insert("network_profile".into(), json!(name));
        }
        Some(NetworkProfile::Off(_)) => {
            network.insert("network_profile".into(), Value::Null);
        }
    }
    (!network.is_empty()).then_some(Value::Object(network))
}

/// Every existing level folder of both chains: the sandbox reads its whole configuration.
fn chain_dirs(resolved: &LaunchConfig) -> Vec<PathBuf> {
    resolved.levels.clone()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::Paths;
    use crate::project::{Relation, Workspace};

    fn resolved(home: &Path, repo: &Path) -> LaunchConfig {
        let paths = Paths {
            home: home.to_path_buf(),
            global: home.join(".config/piton"),
        };
        let ws = Workspace {
            path: repo.to_path_buf(),
            checkout: repo.to_path_buf(),
            relation: Relation::Source,
        };
        crate::config::resolve_launch(&ws, &paths).unwrap()
    }

    fn env(pairs: &[(&str, &str)]) -> Env {
        pairs.iter().map(|(k, v)| (k.to_string(), v.to_string())).collect()
    }

    /// The user's base nono profile, moved into the global `[sandbox]` table, produces the same nono settings.
    #[test]
    fn the_base_profile_round_trips() {
        let dir = tempfile::tempdir().unwrap();
        let home = std::fs::canonicalize(dir.path()).unwrap();
        let global = home.join(".config/piton");
        let repo = home.join("repo");
        std::fs::create_dir_all(&global).unwrap();
        std::fs::create_dir_all(repo.join(".piton/.local")).unwrap();
        std::fs::write(
            global.join("config.toml"),
            r#"
[sandbox]
base = "mise-dev"
groups = ["git_config"]
allow = ["~/.config/pi/agent", "~/Library/Keychains"]
read = ["~/.config"]
read_file = ["~/.ssh/config"]
deny = ["~/secrets.sh"]
unix_socket = ["$SSH_AUTH_SOCK"]
bypass = ["~/Library/Keychains", "~/.ssh/config"]
[sandbox.network]
open_port = [0]
profile = false
"#,
        )
        .unwrap();
        std::fs::write(
            repo.join(".piton/config.toml"),
            "[sandbox]\nallow = [\"~/Library/Caches/org.swift.swiftpm\"]\n",
        )
        .unwrap();
        let p = profile(
            &resolved(&home, &repo),
            &home,
            &env(&[("SSH_AUTH_SOCK", "/private/tmp/agent.sock")]),
            Path::new("/state/agent.sock"),
        )
        .unwrap();
        let h = home.to_string_lossy();
        assert_eq!(p["extends"], "mise-dev");
        assert_eq!(p["groups"]["include"], json!(["git_config"]));
        assert_eq!(p["workdir"]["access"], "readwrite");
        assert_eq!(
            p["filesystem"]["allow"],
            json!([
                format!("{h}/.config/pi/agent"),
                format!("{h}/Library/Keychains"),
                format!("{h}/Library/Caches/org.swift.swiftpm"),
                format!("{h}/repo/.piton/.local"),
            ])
        );
        let read = p["filesystem"]["read"].as_array().unwrap();
        assert_eq!(read[0], format!("{h}/.config"));
        assert!(
            read.contains(&json!(format!("{h}/repo/.piton"))),
            "the chain is readable"
        );
        assert!(!read.contains(&json!(format!("{h}/repo/.piton/.local"))));
        assert_eq!(p["filesystem"]["read_file"], json!([format!("{h}/.ssh/config")]));
        assert_eq!(p["filesystem"]["deny"], json!([format!("{h}/secrets.sh")]));
        // The global grant, then the daemon's socket for sandboxed pis.
        assert_eq!(
            p["filesystem"]["unix_socket"],
            json!(["/private/tmp/agent.sock", "/state/agent.sock"])
        );
        assert_eq!(
            p["filesystem"]["bypass_protection"],
            json!([format!("{h}/Library/Keychains"), format!("{h}/.ssh/config")])
        );
        assert_eq!(p["network"], json!({"open_port": [0], "network_profile": null}));
        assert!(!p["filesystem"].to_string().contains('$'), "every path is literal");
        // The protected files, for this launch's source and checkout.
        let rules = p["unsafe_macos_seatbelt_rules"].as_array().unwrap();
        assert_eq!(rules.len(), 2, "the source's .piton/ and the checkout's .pi/");
        let source = h.replace('.', "\\.");
        assert!(
            rules[0]
                .as_str()
                .unwrap()
                .contains(&format!("(regex #\"^{source}/repo/\\.[pP][iI][tT][oO][nN](/|$)\")")),
            "{}",
            rules[0]
        );
    }

    /// `$VAR` grants come from the daemon's environment, never from pi's (which a repository's mise.toml sets).
    #[test]
    fn variables_come_from_the_daemons_environment() {
        let home = Path::new("/Users/a");
        let daemon = env(&[("TMPDIR", "/private/tmp/x")]);
        assert_eq!(
            expand_grant("$TMPDIR/cache", home, &daemon).unwrap(),
            "/private/tmp/x/cache"
        );
        assert_eq!(
            expand_grant("${TMPDIR}/cache", home, &daemon).unwrap(),
            "/private/tmp/x/cache"
        );
        assert_eq!(expand_grant("~/x", home, &daemon).unwrap(), "/Users/a/x");
        assert!(matches!(
            expand_grant("$UNSET/x", home, &daemon),
            Err(SandboxError::UnsetVariable { .. })
        ));
        let relative = env(&[("REL", "relative")]);
        assert!(matches!(
            expand_grant("$REL", home, &relative),
            Err(SandboxError::NotAbsolute { .. })
        ));
    }

    /// A configuration file linked into a dotfiles repository is readable through its target.
    #[test]
    fn link_targets_are_readable() {
        let dir = tempfile::tempdir().unwrap();
        let home = std::fs::canonicalize(dir.path()).unwrap();
        let global = home.join(".config/piton");
        let dotfiles = home.join("dotfiles");
        let repo = home.join("repo");
        for d in [&global, &dotfiles, &repo] {
            std::fs::create_dir_all(d).unwrap();
        }
        std::fs::write(dotfiles.join("config.toml"), "").unwrap();
        std::os::unix::fs::symlink(dotfiles.join("config.toml"), global.join("config.toml")).unwrap();
        // A linked rules folder needs a recursive grant.
        std::fs::create_dir_all(dotfiles.join("rules")).unwrap();
        std::fs::create_dir_all(global.join("agents")).unwrap();
        std::os::unix::fs::symlink(dotfiles.join("rules"), global.join("agents/rules")).unwrap();
        let p = profile(&resolved(&home, &repo), &home, &Env::new(), Path::new("/s/agent.sock")).unwrap();
        assert_eq!(
            p["filesystem"]["read_file"],
            json!([dotfiles.join("config.toml").to_string_lossy()])
        );
        assert!(
            p["filesystem"]["read"]
                .as_array()
                .unwrap()
                .contains(&json!(dotfiles.join("rules").to_string_lossy()))
        );
    }

    #[test]
    fn defaults_without_configuration() {
        let dir = tempfile::tempdir().unwrap();
        let home = std::fs::canonicalize(dir.path()).unwrap();
        let repo = home.join("repo");
        std::fs::create_dir_all(&repo).unwrap();
        let p = profile(&resolved(&home, &repo), &home, &Env::new(), Path::new("/s/agent.sock")).unwrap();
        assert_eq!(p["extends"], DEFAULT_BASE);
        assert!(p.get("groups").is_none());
        assert!(p.get("network").is_none());
        assert!(p["filesystem"].get("allow").is_none(), "no artifacts folder, no grants");
    }
}
